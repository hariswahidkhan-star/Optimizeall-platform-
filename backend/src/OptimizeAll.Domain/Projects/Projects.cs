using OptimizeAll.Domain.Common;

namespace OptimizeAll.Domain.Projects;

public enum ProjectType
{
    RetainerMonth,
    OneOffCampaign,
    WebsiteBuild,
    SeoProgram,
    SocialContent,
    PaidAdsLaunch,
    EmailProgram,
    Other,
}

public enum ProjectStatus
{
    Planning,
    Active,
    OnHold,
    Completed,
    Cancelled,
}

/// <summary>A piece of client work (a retainer month, campaign, website build…). Client-owned: scoped by IClientScope.</summary>
public class Project : AuditedEntity, IConcurrencyStamped
{
    public Guid ClientAccountId { get; set; }
    public string Name { get; set; } = string.Empty;
    public string? Description { get; set; }
    public ProjectType Type { get; set; }

    /// <summary>Service line slugs, e.g. "seo", "social", "ads", "email", "content", "web", "design".</summary>
    public List<string> ServiceLines { get; set; } = new();
    public DateOnly? StartDate { get; set; }
    public DateOnly? EndDate { get; set; }
    public decimal? BudgetHours { get; set; }
    public decimal? BudgetAmount { get; set; }

    /// <summary>ISO currency of <see cref="BudgetAmount"/> (the client's currency).</summary>
    public string Currency { get; set; } = "USD";

    /// <summary>Hourly rate used for budget burn when no user or role rate applies.</summary>
    public decimal? DefaultHourlyRate { get; set; }
    public ProjectStatus Status { get; set; } = ProjectStatus.Planning;
    public Guid? OwnerUserId { get; set; }

    /// <summary>Template the project was created from (for reference).</summary>
    public string? TemplateKey { get; set; }
    public Guid? CreatedByUserId { get; set; }
    public Guid ConcurrencyStamp { get; set; } = Guid.NewGuid();

    public bool IsRetainer => Type is ProjectType.RetainerMonth or ProjectType.SeoProgram or ProjectType.SocialContent;
}

