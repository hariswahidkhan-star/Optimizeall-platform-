public enum ProjectTaskStatus
{
    Todo,
    InProgress,
    InReview,
    Blocked,
    Done,
}

public enum TaskPriority
{
    Low,
    Normal,
    High,
    Urgent,
}

/// <summary>A unit of work on a project. Kanban position is <see cref="SortOrder"/> within its status column.</summary>
public class ProjectTask : AuditedEntity, IConcurrencyStamped
{
    public Guid ProjectId { get; set; }
    public Guid ClientAccountId { get; set; }
    public Guid? MilestoneId { get; set; }
    public string Title { get; set; } = string.Empty;

    /// <summary>Markdown.</summary>
    public string? Description { get; set; }
    public ProjectTaskStatus Status { get; set; } = ProjectTaskStatus.Todo;
    public TaskPriority Priority { get; set; } = TaskPriority.Normal;
    public DateOnly? DueDate { get; set; }
    public decimal? EstimateHours { get; set; }
    public List<string> Labels { get; set; } = new();

    /// <summary>Shown (title, status, due date, milestone) in the client portal's project view.</summary>
    public bool ClientVisible { get; set; }
    public double SortOrder { get; set; }
    public DateTime? CompletedAt { get; set; }
    public Guid? CreatedByUserId { get; set; }

    /// <summary>Set on tasks generated by a <see cref="RecurringTaskRule"/>: "{ruleId}:{yyyy-MM}" (unique → idempotent).</summary>
    public string? RecurrenceKey { get; set; }
    public Guid? BriefId { get; set; }
    public Guid? MeetingId { get; set; }
    public Guid ConcurrencyStamp { get; set; } = Guid.NewGuid();
}

