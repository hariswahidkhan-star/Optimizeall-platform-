/// <summary>Generates a task every month on <see cref="DayOfMonth"/> (e.g. the monthly report).</summary>
public class RecurringTaskRule : AuditedEntity
{
    public Guid ProjectId { get; set; }
    public Guid ClientAccountId { get; set; }
    public string Title { get; set; } = string.Empty;
    public string? Description { get; set; }

    /// <summary>1–28.</summary>
    public int DayOfMonth { get; set; } = 1;

    /// <summary>Days after generation the task is due.</summary>
    public int DueInDays { get; set; } = 5;
    public Guid? AssigneeUserId { get; set; }
    public decimal? EstimateHours { get; set; }
    public List<string> Labels { get; set; } = new();
    public bool ClientVisible { get; set; }
    public bool IsActive { get; set; } = true;
}

// ---------------------------------------------------------------- templates (reference data)

public sealed record TemplateMilestone(string Key, string Title, int OffsetDays);

public sealed record TemplateTask(
    string Title, string? Description, string? MilestoneKey, int OffsetDays, decimal? EstimateHours, List<string> Labels,
    bool ClientVisible, string? DeliverableType = null);

public sealed record TemplateRecurring(string Title, string? Description, int DayOfMonth, int DueInDays, decimal? EstimateHours, List<string> Labels);

/// <summary>A service template: creating a project from it creates its milestones, tasks and recurring rules.</summary>
public class ProjectTemplate : AuditedEntity, IConcurrencyStamped
{
    public string Key { get; set; } = string.Empty;
    public string Name { get; set; } = string.Empty;
    public string? Description { get; set; }
    public ProjectType ProjectType { get; set; }
    public List<string> ServiceLines { get; set; } = new();
    public decimal? DefaultBudgetHours { get; set; }
    public int? DurationDays { get; set; }
    public List<TemplateMilestone> Milestones { get; set; } = new();
    public List<TemplateTask> Tasks { get; set; } = new();
    public List<TemplateRecurring> Recurring { get; set; } = new();
    public bool IsActive { get; set; } = true;
    public Guid ConcurrencyStamp { get; set; } = Guid.NewGuid();
}

